def build_patch_graph_from_features(patch_features, grid_h=None, grid_w=None, add_positional=True):
    """
    Convert patch_features (tensor [P, F]) into a PyG Data with grid adjacency.
    If grid_h/w not provided, try to infer a square grid (sqrt(P)).
    Returns: Data(x=node_features, edge_index)
    - adds optional positional coords as extra dims if add_positional=True
    """
    # patch_features: torch.Tensor [P, F]
    if not isinstance(patch_features, torch.Tensor):
        patch_features = torch.tensor(patch_features, dtype=torch.float)

    P, F = patch_features.shape

    if grid_h is None or grid_w is None:
        sq = int(math.sqrt(P))
        if sq * sq == P:
            grid_h = grid_w = sq
        else:
            # fallback: try factors. But default to P x 1 if cannot infer
            grid_h = P
            grid_w = 1

    # Node features start with the patch feature vector
    x = patch_features.clone().float()

    if add_positional:
        # add normalized (y,x) grid coordinates as extra two dims
        coords = []
        for idx in range(P):
            r = idx // grid_w
            c = idx % grid_w
            coords.append([r / (grid_h - 1) if grid_h>1 else 0.0, c / (grid_w - 1) if grid_w>1 else 0.0])
        coords = torch.tensor(coords, dtype=torch.float)
        x = torch.cat([x, coords], dim=1)  # new dim F+2

    # Build 4-neighbour grid adjacency (or 8-neighbour if you want)
    edge_list = []
    for r in range(grid_h):
        for c in range(grid_w):
            i = r * grid_w + c
            # right neighbour
            if c + 1 < grid_w:
                j = r * grid_w + (c+1)
                edge_list.append([i, j]); edge_list.append([j, i])
            # down neighbour
            if r + 1 < grid_h:
                j = (r+1) * grid_w + c
                edge_list.append([i, j]); edge_list.append([j, i])
            # (optional) diagonal neighbours - comment out if not wanted
            # if r+1 < grid_h and c+1 < grid_w:
            #     j = (r+1)*grid_w + (c+1)
            #     edge_list.append([i,j]); edge_list.append([j,i])

    if len(edge_list) == 0:
        edge_index = torch.empty((2,0), dtype=torch.long)
    else:
        edge_index = torch.tensor(edge_list, dtype=torch.long).t().contiguous()

    data = Data(x=x, edge_index=edge_index)
    return data, (grid_h, grid_w)

class GATAutoEncoder(nn.Module):
    def __init__(self, in_dim, hidden_dim=256, latent_dim=128, heads=4, dropout=0.2):
        super().__init__()
        self.encoder1 = GATConv(in_dim, hidden_dim // heads, heads=heads, concat=True, dropout=dropout)
        self.encoder2 = GATConv(hidden_dim, latent_dim // heads, heads=heads, concat=True, dropout=dropout)

        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Linear(hidden_dim // 2, in_dim)
        )

    def forward(self, x, edge_index):
        h = torch.relu(self.encoder1(x, edge_index))
        h = torch.relu(self.encoder2(h, edge_index))
        recon = self.decoder(h)
        return recon, h

class GATAutoencoder(nn.Module):
    def __init__(self, in_channels, hidden_channels=128, dropout=0.2):
        super(GATAutoencoder, self).__init__()
        self.encoder = GATConv(in_channels, hidden_channels, heads=2, concat=True)
        self.decoder = nn.Sequential(
            nn.Linear(hidden_channels * 2, in_channels),
            nn.ReLU(),
            nn.Linear(in_channels, in_channels)
        )
        self.dropout = dropout

    def forward(self, x, edge_index):
        # Encoder
        x = F.elu(self.encoder(x, edge_index))
        x = F.dropout(x, p=self.dropout, training=self.training)
        # Decoder
        x_recon = self.decoder(x)
        return x_recon

