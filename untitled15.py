def infer_image_anomaly(image_path, backbone, gat_model):
    """
    Infers anomaly score for a single image and returns heatmap + image-level score.
    """
    img = Image.open(image_path).convert("RGB")

    # Get patch-level anomaly map (heatmap) and patch scores
    heatmap, patch_scores = gat_ae_infer_image_heatmap(img, backbone, gat_model)

    # Convert patch_scores → tensor if not already
    patch_scores = torch.tensor(patch_scores).float()

    # Compute image-level anomaly score (mean of all patches)
    image_score = patch_scores.mean().item()

    return heatmap, image_score


