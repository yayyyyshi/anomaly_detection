def gat_ae_infer_image_heatmap(image_pil, backbone_model, gat_model, up_size=(224,224)):
    """
    image_pil: PIL.Image
    returns: segm_map_upsampled (H,W) as numpy array, per_patch_scores (P,)
    """
    backbone_model.eval()
    gat_model.eval()

    inp = transform(image_pil).unsqueeze(0).to(device)
    with torch.no_grad():
        patch = backbone_model(inp)  # [P, feat_dim]
    # build graph
    data, (gh, gw) = build_patch_graph_from_features(patch.cpu(), grid_h=None, grid_w=None, add_positional=True)
    data.x = data.x.to(device)
    data.edge_index = data.edge_index.to(device)

    with torch.no_grad():
        recon = gat_model(data.x, data.edge_index)
    # compute per-node MSE between recon_feat and original feat
    feat_dim = patch.shape[1]
    recon_feat = recon[:, :feat_dim]
    orig_feat = data.x[:, :feat_dim]
    # per-node MSE
    per_node_mse = torch.mean((recon_feat - orig_feat)**2, dim=1)  # [P,]
    per_node_mse = per_node_mse.cpu().numpy()

    # reshape to grid and upsample to image size
    P = per_node_mse.shape[0]
    # infer grid dims
    sq = int(math.sqrt(P))
    if sq*sq == P:
        gh = gw = sq
    else:
        # fallback: try to use previously returned gh, gw
        gh, gw = gh, gw

    segm_map = per_node_mse.reshape(1, 1, gh, gw).astype(np.float32)  # 1x1xhxw
    segm_map_t = torch.tensor(segm_map)
    segm_up = F.interpolate(segm_map_t, size=up_size, mode='bilinear', align_corners=False)
    segm_up = segm_up.squeeze().cpu().numpy()
    # normalize to 0..1
    segm_up = (segm_up - segm_up.min()) / (segm_up.max() - segm_up.min() + 1e-8)

    return segm_up, per_node_mse

